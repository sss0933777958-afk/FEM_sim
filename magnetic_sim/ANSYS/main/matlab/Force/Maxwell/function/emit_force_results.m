function emit_force_results(matfile)
%EMIT_FORCE_RESULTS  Force self-consistency .mat -> LaTeX -> xelatex -> PDF.
%
%   emit_force_results(matfile)
%
%   Two sections only, mirroring the flux calibration PDF: the measurement
%   parameters the force was generated from, and the parameters recovered by
%   refitting it. Output:
%
%     results/<model>/<single|eighteen>/<rec.stem>.pdf
%
%   [MODIFIED 2026-09-02] Base-generic. Every symbol printed comes from
%   rec.labels (written by solve_force), so a voltage run prints D bar, V,
%   mT/mV and pN/mV^2 wherever a current run prints K_I bar, I, mT/A and
%   pN/A^2. The file name comes from rec.stem, built once in main.m.
%
%   Only the PDF is kept; .tex/.aux/.log are deleted (results-pdf-only rule).
%
%   See also FITTING_FORCE, SOLVE_FORCE, BASE_MODEL.

    rec = load(matfile);
    rec = backfill(rec);
    T   = emit_tex();
    lb  = rec.labels;

    here = fileparts(mfilename('fullpath'));                 % .../Force/Maxwell/function
    FMX  = fileparts(here);                                  % .../Force/Maxwell
    sub  = 'single';  if rec.USE_BIAS, sub = 'eighteen'; end
    out_dir = fullfile(FMX, 'results', rec.model, sub);
    if ~exist(out_dir, 'dir'), mkdir(out_dir); end

    stem     = rec.stem;
    tex_path = fullfile(out_dir, [stem '.tex']);
    pdf_path = fullfile(out_dir, [stem '.pdf']);
    pole = {'P1','P2','P3','P4','P5','P6'};

    fid = fopen(tex_path, 'w');
    fprintf(fid, '%% Auto-generated by emit_force_results.m\n');
    fprintf(fid, '\\documentclass[11pt]{article}\n');
    fprintf(fid, '\\usepackage[margin=1in]{geometry}\n\\usepackage{amsmath}\n');
    fprintf(fid, '\\setlength{\\parindent}{0pt}\n\\begin{document}\n');

    fprintf(fid, '\\section*{Force model self-consistency: %s base}\n', rec.base);
    fprintf(fid, '\\texttt{%s} / \\texttt{%s}, %d points, $R\\le%g~\\mu$m\n', ...
            texesc(rec.model), texesc(rec.MATNAME), rec.npts, rec.R_select);
    fprintf(fid, '\\[ {}^{M}g_{B} = %.4g~\\mathrm{A}\\,\\mu\\mathrm{m}^{2}/\\mathrm{mT} \\]\n', rec.mgB);

    % The two relations that define the gauge. F g is the whole prefactor, so
    % the square root sits on F H, not inside F g.
    fprintf(fid, '\\[ %s = \\frac{U_{F}\\,{}^{M}g_{B}}{2\\hat{\\ell}}\\bigl(%s\\bigr)^{2}, \\qquad U_{F} = %g \\]\n', ...
            lb.gF_tex, lb.gB_tex, rec.UF);
    fprintf(fid, '\\[ %s = \\sqrt{%s}\\;%s \\]\n', lb.H_tex, lb.gF_tex, lb.M_tex);

    % ---- measurement side (the flux calibration f_m was generated from) ----
    fprintf(fid, '\\subsection*{Measure}\n');
    fprintf(fid, '\\[ \\hat{\\ell}_{m} = %.4f~\\mu\\mathrm{m} \\]\n', rec.l_m);
    T.scalar_unit(fid, lb.gB_tex_m, rec.gB_m, lb.gB_texu);
    T.scalar_unit(fid, lb.gF_tex_m, rec.gF_m, lb.gF_texu);
    T.mat(fid, lb.M_tex_m, rec.Mbar_m, pole, '');
    % [ADDED] the excitation matrix itself: column j is u_j, the excitation that
    % produced f_m for pole j. Voltage -> V [mV] (the sensor read-out), current
    % -> F [A]. No auto-factor (user decision): the entries are printed as the
    % actual mV, not as a mantissa with a 10^3 pulled out in front.
    T.mat(fid, sprintf('%s~[\\mathrm{%s}]', lb.u_tex, lb.u_unit), rec.u, pole, '');
    if rec.USE_BIAS
        T.mat(fid, '(e/\hat{\ell})_{m}', e2E36(rec.e_m), pole, '');
    end

    % ---- recovered side ----------------------------------------------------
    fprintf(fid, '\\subsection*{Calibration}\n');
    fprintf(fid, '\\[ \\hat{\\ell} = %.4f~\\mu\\mathrm{m} \\]\n', rec.l_hat);
    T.scalar_unit(fid, lb.gF_tex, rec.gF_hat, lb.gF_texu);
    T.scalar_unit(fid, lb.gB_tex, rec.gB_hat, lb.gB_texu);
    T.mat(fid, lb.M_tex, rec.Mbar_hat, pole, '');
    if rec.USE_BIAS
        T.mat(fid, 'e/\hat{\ell}', e2E36(rec.e_hat), pole, '');
    end
    T.mat(fid, lb.H_tex, rec.H_hat, pole, '');
    fprintf(fid, '\\[ \\mathrm{RMS~residual} = %s~\\mathrm{pN} \\]\n', sci(rec.rms));

    fprintf(fid, '\\end{document}\n');
    fclose(fid);

    % ---- inline xelatex (results keeps the pdf only) -----------------------
    xelatex = 'C:\Users\Kuo\AppData\Local\Programs\MiKTeX\miktex\bin\x64\xelatex.exe';
    old = cd(out_dir);
    [st, so] = system(sprintf('"%s" -interaction=nonstopmode -halt-on-error "%s"', xelatex, tex_path));
    cd(old);
    if st ~= 0 || ~exist(pdf_path, 'file')
        disp(so);  error('emit_force_results:xelatex', 'xelatex failed');
    end
    for ext = {'.tex','.aux','.log','.out'}
        f = fullfile(out_dir, [stem ext{1}]);
        if exist(f,'file'), delete(f); end
    end
    fprintf('saved %s\n', pdf_path);
end

% ---- accept records written before the generic naming -----------------------
%   Field renames (KI_* -> Mbar_*, gI_* -> gB_*, I_set -> u) and the two fields
%   that are now built in main.m (labels, stem). The gains are DERIVED from
%   c_m/s_m and h11 rather than read back, because gF was absent in the first
%   generation of records and square-rooted in the second.
function rec = backfill(rec)
    if ~isfield(rec,'base'), rec.base = 'current'; end
    if ~isfield(rec,'Mbar_hat') && isfield(rec,'KI_hat'), rec.Mbar_hat = rec.KI_hat; end
    if ~isfield(rec,'Mbar_m')   && isfield(rec,'KI_m'),   rec.Mbar_m   = rec.KI_m;   end
    if ~isfield(rec,'gB_hat')   && isfield(rec,'gI_hat'), rec.gB_hat   = rec.gI_hat; end
    if ~isfield(rec,'gB_m')     && isfield(rec,'gI_m'),   rec.gB_m     = rec.gI_m;   end
    if ~isfield(rec,'u')        && isfield(rec,'I_set'),  rec.u        = rec.I_set;  end
    if ~isfield(rec,'c_m')      && isfield(rec,'s_m'),    rec.c_m      = rec.s_m;    end
    rec.gF_m   = rec.c_m;                     % F g,m is the prefactor itself
    rec.gF_hat = (6 * rec.h11 / 5)^2;         % since F H = sqrt(F g) * Mbar
    if ~isfield(rec,'labels')
        [~,~,~,o] = solve_force(rec.H_hat, rec.mgB, rec.l_hat, rec.UF, rec.base);
        rec.labels = o.labels;
    end
    if ~isfield(rec,'stem')
        v = regexprep(rec.VARIANT, '^maxwell_?', '');
        v = regexprep(v, '_?axshN\d+', '');
        if ~isempty(v), v = ['_' v]; end
        rec.stem = sprintf('%s_R%d_N%d%s', rec.base, round(rec.R_select), rec.npts, v);
    end
end

% ---- 17 offsets -> 3x6 matrix (same e6z constraint as build_L) --------------
function E36 = e2E36(e17)
    E36 = zeros(3,6);
    E36(:,1)=e17(1:3);   E36(:,2)=e17(4:6);   E36(:,3)=e17(7:9);
    E36(:,4)=e17(10:12); E36(:,5)=e17(13:15);
    E36(1,6)=e17(16);    E36(2,6)=e17(17);
    E36(3,6)=e17(1)-e17(4)+e17(8)-e17(11)+e17(15);
end

% ---- LaTeX scientific notation (a raw 2.7e-11 renders as "2.7e minus 11") ---
function t = sci(v)
    if v == 0
        t = '0';
    else
        ex = floor(log10(abs(v)));
        if abs(ex) < 3
            t = sprintf('%.4g', v);
        else
            t = sprintf('%.3f\\times10^{%d}', v/10^ex, ex);
        end
    end
end

function s = texesc(v)
    s = strrep(v, '_', '\_');
end
