                    mean(e_q(1:N_j,:),'all'), std(e_q(1:N_j,:),0,'all'), max(e_q(1:N_j,:),[],'all'), mean(e_q(N_j+1:end,:),'all'), std(e_q(N_j+1:end,:),0,'all'), max(e_q(N_j+1:end,:),[],'all'), rms(res(:)));
