            d_hat = Amat \ y_m;                                % d_hat_m = (A'A)^-1 A' y_m
            t_fit = toc(t0);
            d = reshape(d_hat, 10, N_j, 5);  x = reshape(reshape(d, 10, []) .* sc, [], 1);
            t_lab = sum(F.T1);  N_grb = sum(F.NGRB);
