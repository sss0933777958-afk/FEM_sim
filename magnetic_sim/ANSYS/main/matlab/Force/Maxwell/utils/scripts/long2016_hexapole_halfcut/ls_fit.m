            [~, ic_] = min(vecnorm(P, 2, 2));  V_ = zeros(5, N_j);
            for j = 1:N_j
                Zj = squeeze(z_(:,j,:));  rf = Zj(:,ic_);
                for it_ = 1:5, sg = sign(rf.' * Zj);  sg(sg == 0) = 1;  rf = mean(Zj .* sg, 2); end
                z_(:,j,:) = reshape(Zj .* sg, 5, 1, N_p);  V_(:,j) = rf / norm(rf);
