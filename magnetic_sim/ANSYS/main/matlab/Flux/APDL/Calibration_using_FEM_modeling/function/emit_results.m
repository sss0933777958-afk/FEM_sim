function emit_results(matfile)
%EMIT_RESULTS  讀校正結果 .mat（自描述、含 base/設定）→ 排版 LaTeX → xelatex → PDF。
%   emit_results(matfile)
%   依 rec.base 分 current / voltage 兩版；落點
%     results/<model>/<eighteen|single>/model_results_<base>_<variant>.pdf
%   （single=USE_BIAS false、eighteen=true）。清中間檔只留 pdf。
    rec = load(matfile);
    T   = emit_tex();

    here = fileparts(mfilename('fullpath'));                 % .../function
    CAL  = fileparts(here);                                  % .../Calibration_using_FEM_modeling
    sub  = 'single'; if rec.USE_BIAS, sub = 'eighteen'; end
    out_dir = fullfile(CAL, 'results', rec.model, sub);
    if ~exist(out_dir,'dir'), mkdir(out_dir); end
    % [ADDED 2026-08-03] 取樣半徑非定案 150µm → 檔名加 _R<NNN>，不覆蓋既有 R150 結果（與 Maxwell 分支同步）
    rsfx = '';
    if isfield(rec,'R_select') && abs(rec.R_select - 150e-6) > 1e-12
        rsfx = sprintf('_R%d', round(rec.R_select*1e6));
    end
    stem     = sprintf('model_results_%s_%s%s', rec.base, rec.VARIANT, rsfx);
    tex_path = fullfile(out_dir, [stem '.tex']);
    pdf_path = fullfile(out_dir, [stem '.pdf']);
    pole = {'P1','P2','P3','P4','P5','P6'};

    fid = fopen(tex_path, 'w');
    fprintf(fid, '%% Auto-generated by emit_results.m\n');
    fprintf(fid, '\\documentclass[11pt]{article}\n\\usepackage[margin=1in]{geometry}\n\\usepackage{amsmath}\n\\begin{document}\n');

    % [MODIFIED 2026-10-03] 印出項目與順序照 .claude/rules/calibration-transfer-matrix-output.md：
    %   current: g_I, K_I_bar, H_I, l_hat, e_hat, RMS；voltage: g_V, M_bar, H_V, l_hat, e_hat, V, RMS。
    switch rec.base
        case 'current'
            T.scalar_unit(fid, '{}^{B}\hat{g}_{I}', rec.gI_hat, 'mT/A');
            T.mat(fid, '\bar{K}_{I}', rec.KI_bar, pole, '');
            T.mat(fid, '{}^{B}\hat{H}_{I}~[\mathrm{mT/A}]', rec.gI_hat * rec.KI_bar, pole, '');
            fprintf(fid, '\\[ \\hat{\\ell} = %.1f~\\mu\\mathrm{m} \\]\n', rec.l_hat*1e6);
            emit_e(fid, rec, T, pole);
        case 'voltage'
            % V 的欄是激發 coil 序 -> 重排成 paper P1..P6（M_bar / H_V 本就是 paper 序）
            p2a = zeros(1,6);  p2a(rec.apdl_to_paper_idx) = 1:6;    % paper 欄 <- coil 欄
            T.scalar_unit(fid, '{}^{B}\hat{g}_{V}', rec.gV_hat, 'mT/mV');
            T.mat(fid, '\bar{M}', rec.D_bar, pole, '');             % .mat 欄位名沿用 D_bar
            T.mat(fid, '{}^{B}\hat{H}_{V}~[\mathrm{mT/mV}]', rec.gV_hat * rec.D_bar, pole, 'auto');
            fprintf(fid, '\\[ \\hat{\\ell} = %.1f~\\mu\\mathrm{m} \\]\n', rec.l_hat*1e6);
            emit_e(fid, rec, T, pole);
            T.mat(fid, 'V~[\mathrm{mV}]', rec.V(:,p2a), pole, '');
        otherwise
            fclose(fid); error('emit_results: unknown base ''%s''', rec.base);
    end
    emit_rms(fid, rec);
    fprintf(fid, '\\end{document}\n');
    fclose(fid);

    % inline xelatex（results 只留 pdf）
    xelatex = 'C:\Users\Kuo\AppData\Local\Programs\MiKTeX\miktex\bin\x64\xelatex.exe';
    old = cd(out_dir);
    [st, so] = system(sprintf('"%s" -interaction=nonstopmode -halt-on-error "%s"', xelatex, tex_path));
    cd(old);
    if st ~= 0 || ~exist(pdf_path,'file')
        disp(so); error('xelatex 編譯失敗');
    end
    for ext = {'.tex','.aux','.log','.out'}
        f = fullfile(out_dir, [stem ext{1}]);
        if exist(f,'file'), delete(f); end
    end
    fprintf('已存 %s\n', pdf_path);
end

% ---- e_hat：無因次偏移（以 l_hat 為長度單位）；single 時 e = 0 不印 ----
function emit_e(fid, rec, T, pole)
    if rec.USE_BIAS
        T.mat(fid, '\hat{e}', e2E36(rec.e), pole, '');
    end
end

% ---- 校正誤差 RMS = sqrt(J/(3*M*N))：J = 校正點殘差平方和 [mT^2]、3 分量、M 激發數、N 校正點數 ----
function emit_rms(fid, rec)
    assert(isfield(rec,'J') && isfield(rec,'npts'), 'emit_results: .mat 缺 J 或 npts，無法算校正誤差 RMS');
    M = 6;   if isfield(rec,'G') && ~isempty(rec.G), M = size(rec.G, 2); end
    fprintf(fid, '\\[ \\mathrm{RMS} = \\sqrt{J/(3 \\cdot %d \\cdot N)} = %.4g~\\mathrm{mT}, \\quad N = %d \\]\n', ...
            M, sqrt(rec.J / (3 * M * rec.npts)), rec.npts);
end

% ---- 由 17 偏移建 E36（3×6，含 e6z 約束；不加 Pc_base）----
function E36 = e2E36(e17)
    E36 = zeros(3,6);
    E36(:,1)=e17(1:3);   E36(:,2)=e17(4:6);   E36(:,3)=e17(7:9);
    E36(:,4)=e17(10:12); E36(:,5)=e17(13:15);
    E36(1,6)=e17(16);    E36(2,6)=e17(17);
    E36(3,6)=e17(1)-e17(4)+e17(8)-e17(11)+e17(15);
end
