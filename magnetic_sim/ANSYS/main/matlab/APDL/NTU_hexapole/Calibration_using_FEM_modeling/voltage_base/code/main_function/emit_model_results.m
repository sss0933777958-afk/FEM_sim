function emit_model_results(VARIANT, USE_BIAS)
% EMIT_MODEL_RESULTS  Hall-sensor 校正結果，Hall 表格式一檔輸出
%   D̄ / G / V / ℓ̂ / ^Bĝ_V（18-param bias 時再加印 ê [µm]）。純結果（無 caption）、
%   單位標題（無因次/10^0 不標，per figure-style.md）。由 main.m 於最後一步呼叫（存完 .mat 後）。
%   輸出：voltage_base/results/{single_param|eighteen_param}/model_results_<variant>.pdf。

    if nargin<1 || isempty(VARIANT), VARIANT = 'gap_calibrate'; end
    here   = fileparts(mfilename('fullpath'));
    base   = fileparts(fileparts(here));                  % .../voltage_base
    S = load(fullfile(base,'data',sprintf('calib_D_%s.mat',VARIANT)));   % 全載（含 USE_BIAS 若有）
    if nargin>=2 && ~isempty(USE_BIAS), ub = USE_BIAS; elseif isfield(S,'USE_BIAS'), ub = S.USE_BIAS; else, ub = true; end
    sub = 'single_param'; if ub, sub = 'eighteen_param'; end
    out_dir = fullfile(base,'results',sub);              % 依模型分子夾
    if ~exist(out_dir,'dir'); mkdir(out_dir); end
    D_bar    = S.D_bar;      % 無因次（D̄(1,1)=5/6）
    G        = S.Dv_p;       % [mT]
    V        = S.Vmat_p;     % [mV]
    ell_hat  = S.ell_hat;    % [µm]
    ghat_V_B = S.g_V;        % [mT/mV]

    fprintf('ℓ̂=%.1f µm, ^Bĝ_V=%.4e mT/mV\n', ell_hat, ghat_V_B);

    pole = {'P1','P2','P3','P4','P5','P6'};
    tex_path = fullfile(out_dir, sprintf('model_results_%s.tex', VARIANT));
    pdf_path = fullfile(out_dir, sprintf('model_results_%s.pdf', VARIANT));
    T = emit_tex();
    fid = fopen(tex_path,'w');
    fprintf(fid,'%% Auto-generated by emit_model_results.m\n');
    fprintf(fid,'\\documentclass[11pt]{article}\n\\usepackage[margin=1in]{geometry}\n\\usepackage{amsmath}\n\\begin{document}\n');
    T.mat(fid, '\bar{D}', D_bar, pole, '');              % 無因次 → 不標單位
    T.mat(fid, 'G~[\mathrm{mT}]', G, pole, '');
    T.mat(fid, 'V~[\mathrm{mV}]', V, pole, '');
    fprintf(fid,'\\[\n\\hat{\\ell} = %.1f~\\mu\\mathrm{m}\n\\]\n', ell_hat);
    T.scalar_unit(fid, '{}^{B}\hat{g}_{V}', ghat_V_B, 'mT/mV');   % 10^0 不標
    if ub && isfield(S,'E36')                                    % 18-param bias：加印 ê 物理偏移 e=ℓ̂·ê [µm]
        T.e(fid, 'e~[\mu\mathrm{m}]', ell_hat .* S.E36, pole, '');
    end
    fprintf(fid,'\\end{document}\n');
    fclose(fid);

    xelatex = 'C:\Users\Kuo\AppData\Local\Programs\MiKTeX\miktex\bin\x64\xelatex.exe';
    old = cd(out_dir);
    [st,so] = system(sprintf('"%s" -interaction=nonstopmode -halt-on-error "%s"', xelatex, tex_path));
    cd(old);
    if st~=0 || ~exist(pdf_path,'file'); fprintf('%s\n',so); error('xelatex 編譯失敗'); end
    for e = {'.tex','.aux','.log','.out'}, f = fullfile(out_dir, sprintf('model_results_%s%s', VARIANT, e{1})); if exist(f,'file'); delete(f); end, end
    fprintf('已存 %s\n', pdf_path);
end
