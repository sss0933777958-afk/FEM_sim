function emit_model_results(USE_BIAS, VARIANT, R_um)
% EMIT_MODEL_RESULTS  點電荷模型結果，Hall 表格式一檔輸出（K̄_I / ℓ̂ / G / F / ^Bĝ_I [/ ê]）。
%   USE_BIAS=true  → 18-param bias（載 fit_bias_*.mat）→ results/eighteen_param/。
%   USE_BIAS=false → single-parameter fix（載 fit_fixl_*.mat，無 ê 段）→ results/single_param/。
%   純結果（無 caption）、單位標題（無因次/10^0 不標）。由 main.m 於最後一步呼叫（存完 .mat 後）。
%   F = 1A × I₆；G = ^Bĝ_I·K̄·F（mT）；ê 由 e_hat(17) 依 e6z 約束重建（僅 bias）。

    if nargin<1 || isempty(USE_BIAS), USE_BIAS = true; end
    if nargin<2 || isempty(VARIANT), VARIANT = 'gap_calibrate'; end
    if nargin<3 || isempty(R_um), R_um = 150; end
    tag = 'fixl'; sub = 'single_param';  if USE_BIAS, tag = 'bias'; sub = 'eighteen_param'; end
    here   = fileparts(mfilename('fullpath'));
    base   = fileparts(fileparts(here));                  % .../current_base
    out_dir = fullfile(base,'results',sub);              % 依模型分子夾
    if ~exist(out_dir,'dir'); mkdir(out_dir); end

    S = load(fullfile(base,'data',sprintf('fit_%s_R%03dum_%s.mat',tag,R_um,VARIANT)));   % fit_fixl_ / fit_bias_
    coil_sign = [1 -1 1 -1 -1 1];               % all-source 顯示翻號（欄縮放翻上極 P2/P4/P5；同 write_KbarI_tex）
    K_bar    = S.Khat .* coil_sign;             % K̄_I（無因次，K̄(1,1)=5/6）→ 對角全正、off-diag 全負
    ell      = S.ell;       % ℓ̂ [µm]
    ghat_I_B = S.gB;        % ^Bĝ_I [mT/A]
    hasAiso  = isfield(S,'C_mean') && isfield(S,'kappa_mean');     % 控制範圍性能量
    I_A = 1;                % 激發電流 [A]
    F = I_A * eye(6);       % 電流矩陣 [A]
    G = ghat_I_B * K_bar * F;   % [mT]（用翻號後 K̄ → G 上極對角也轉正）
    e = S.e_hat;                                   % 17-vec bias
    E36 = zeros(3,6);                              % 重建 ê(3×6)（含 e6z 約束）
    E36(:,1)=e(1:3); E36(:,2)=e(4:6); E36(:,3)=e(7:9); E36(:,4)=e(10:12); E36(:,5)=e(13:15);
    E36(1,6)=e(16);  E36(2,6)=e(17);  E36(3,6)=e(1)-e(4)+e(8)-e(11)+e(15);

    fprintf('ℓ̂=%.1f µm, ^Bĝ_I=%.4e mT/A\n', ell, ghat_I_B);

    pole = {'P1','P2','P3','P4','P5','P6'};
    tex_path = fullfile(out_dir, sprintf('model_results_%s.tex', VARIANT));
    pdf_path = fullfile(out_dir, sprintf('model_results_%s.pdf', VARIANT));
    T = emit_tex();
    fid = fopen(tex_path,'w');
    fprintf(fid,'%% Auto-generated by emit_model_results.m\n');
    fprintf(fid,'\\documentclass[11pt]{article}\n\\usepackage[margin=1in]{geometry}\n\\usepackage{amsmath}\n\\begin{document}\n');
    T.mat(fid, '\bar{K}_{I}', K_bar, pole, '');          % 無因次 → 不標單位
    fprintf(fid,'\\[\n\\hat{\\ell} = %.1f~\\mu\\mathrm{m}\n\\]\n', ell);
    T.mat(fid, 'G~[\mathrm{mT}]', G, pole, '');
    T.mat(fid, 'F~[\mathrm{A}]', F, pole, '');
    T.scalar_unit(fid, '{}^{B}\hat{g}_{I}', ghat_I_B, 'mT/A');   % 10^0 不標
    if USE_BIAS, T.e(fid, 'e~[\mu\mathrm{m}]', ell.*E36, pole, ''); end   % 3×6 物理偏移 e=ℓ̂·ê [µm]（僅 bias；fix 無 ê 段）
    if hasAiso   % 控制範圍性能量（singular_value.pdf）：C_mean=體積 ∏σ_k(有單位)、kappa_mean=σmin/σmax(無因次不標)
        fprintf(fid,'\\[\n \\mathcal{C}_{\\mathrm{mean}} = %.4g~(\\mathrm{mT/A})^{3}\n\\]\n', S.C_mean);
        fprintf(fid,'\\[\n \\kappa_{\\mathrm{mean}} = %.4f\n\\]\n', S.kappa_mean);
        if isfield(S,'Np_range')
            fprintf(fid,'\\noindent\\small $\\mathcal{C}_{\\mathrm{mean}}=\\overline{\\prod_k\\sigma_k}$, $\\kappa_{\\mathrm{mean}}=\\overline{\\sigma_{\\min}/\\sigma_{\\max}}$ over %d real nodes in $R\\le150~\\mu$m ball.\n', S.Np_range);
        end
    end
    fprintf(fid,'\\end{document}\n');
    fclose(fid);

    xelatex = 'C:\Users\Kuo\AppData\Local\Programs\MiKTeX\miktex\bin\x64\xelatex.exe';
    old = cd(out_dir);
    [st,so] = system(sprintf('"%s" -interaction=nonstopmode -halt-on-error "%s"', xelatex, tex_path));
    cd(old);
    if st~=0 || ~exist(pdf_path,'file'); fprintf('%s\n',so); error('xelatex 編譯失敗'); end
    for e2 = {'.tex','.aux','.log','.out'}, f = fullfile(out_dir, sprintf('model_results_%s%s', VARIANT, e2{1})); if exist(f,'file'); delete(f); end, end
    fprintf('已存 %s\n', pdf_path);
end
